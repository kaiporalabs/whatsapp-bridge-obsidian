import {Message,Settings,escapeText,folderPath,messageKey} from './core';

export type MediaKind='image'|'video'|'document'|'sticker';
export interface MediaRecord{key:string;kind:MediaKind;chat:string;chatName:string;sender:string;timestamp:string;note:string;path:string;name:string;status:'downloaded'|'download_failed';error:string;}
const safe=(value:string)=>escapeText(value).replace(/\n/g,' ');
const kind=(value:string):MediaKind|null=>{
  const v=value.toLowerCase();if(v==='sticker'||v.includes('webp-sticker'))return'sticker';if(v==='photo'||v.startsWith('image'))return'image';if(v==='gif'||v.startsWith('video'))return'video';if(['document','file'].includes(v)||v.startsWith('application/'))return'document';return null;
};
export function mediaKind(message:Message){return kind(message.mediaType);}
export function mediaEnabled(s:Settings,message:Message){const k=mediaKind(message);return k==='image'?s.downloadImages:k==='video'?s.downloadVideos:k==='document'?s.downloadDocuments:k==='sticker'?s.downloadStickers:false;}
const root=(s:Settings)=>s.storageFormat==='local-sync'?folderPath(s.folder):`${folderPath(s.folder)}/${s.source}`;
const subfolder=(k:MediaKind)=>k==='image'?'Images':k==='video'?'Videos':k==='document'?'Documents':'Stickers';
export function mediaBase(s:Settings,k:MediaKind){return `${root(s)}/${folderPath(s.mediaFolder)}/${subfolder(k)}`;}
export function mediaIndexPath(s:Settings){return `${root(s)}/Media Index.md`;}
export function mediaKey(s:Settings,m:Message){return messageKey(s.source,m);}
export function deterministicMediaPath(s:Settings,m:Message,extension:string){
  const k=mediaKind(m)??'document',ext=/^\.[a-z0-9]{1,10}$/i.test(extension)?extension.toLowerCase():'.bin';
  return `${mediaBase(s,k)}/${k}-${mediaKey(s,m).slice(0,24)}${ext}`;
}
export function findIndexedMedia(content:string,key:string){
  const block=content.match(new RegExp(`<!-- wa-media-index:${key}:start -->\\n([\\s\\S]*?)\\n<!-- wa-media-index:${key}:end -->`))?.[1]??'';
  return block.match(/^- File: \[\[([^|\]\n]+)(?:\|[^\]]*)?\]\]$/m)?.[1]??'';
}
export function updateMediaIndex(existing:string,record:MediaRecord){
  const title=existing?existing:'# WhatsApp Media Index\n\nGenerated by WhatsApp Bridge. Entries are keyed by account, conversation and message ID.\n';
  const note=record.note.replace(/\.md$/,''),error=record.error?`\n- Error: ${safe(record.error)}`:'',file=record.path?`[[${record.path}|${safe(record.name||record.kind)}]]`:'Unavailable';
  const block=`<!-- wa-media-index:${record.key}:start -->\n## ${record.timestamp.replace('T',' ').replace('.000Z',' UTC')} — ${safe(record.chatName)}\n\n- Type: ${record.kind}\n- Conversation: [[${note}|${safe(record.chatName)}]]\n- Chat ID: \`${safe(record.chat)}\`\n- Sender: ${safe(record.sender)}\n- Sent: ${record.timestamp}\n- File: ${file}\n- Status: ${record.status}${error}\n<!-- wa-media-index:${record.key}:end -->`;
  const pattern=new RegExp(`<!-- wa-media-index:${record.key}:start -->[\\s\\S]*?<!-- wa-media-index:${record.key}:end -->`);
  return pattern.test(title)?title.replace(pattern,()=>block):`${title.trimEnd()}\n\n${block}\n`;
}
function display(m:Message,path:string){const k=mediaKind(m),label=safe(m.mediaName||k||'media');return k==='document'?`[[${path}|${label}]]`:`![[${path}]]`;}
export function mergeMediaIntoNote(existing:string,s:Settings,m:Message,path:string){
  const key=mediaKey(s,m);if(!/^[a-f0-9]{64}$/.test(key)||!path)return existing;
  const block=`<!-- wa-media:${key}:start -->\n${display(m,path)}\n<!-- wa-media:${key}:end -->`,pattern=new RegExp(`<!-- wa-media:${key}:start -->[\\s\\S]*?<!-- wa-media:${key}:end -->`);
  if(pattern.test(existing))return existing.replace(pattern,()=>block);
  if(s.storageFormat==='local-sync'){
    const heading='## Imported media history',prefix=existing.includes(heading)?'':`\n\n${heading}\n`;
    const meta=`**${m.timestamp.replace('T',' ').replace('.000Z',' UTC')} — ${safe(m.fromMe?s.ownName:m.sender)}**\n\n`;
    return `${existing.trimEnd()}${prefix}\n\n${meta}${block}\n`;
  }
  const marker=`<!-- wa-bridge:${key} -->`;if(!existing.includes(marker))return existing;const position=existing.indexOf(marker)+marker.length;
  return `${existing.slice(0,position)}\n${block}${existing.slice(position)}`;
}
